#!/usr/bin/env node
// Writes lib/city-configs.js, GENERATED: the runtime facts of every city built by docs/multi-city/city-build.md (time
// zone, holidays, map view, fine), read by its page (lib/city.js) and the alert server (lib/cities.js). One entry per
// data/<id>/ that has both city.json and segments.json. Boston is built by hand (lib/city-boston.js) and left out.
// Also writes the public cities (scripts/cities/public.mjs) into index.html's CITY_MAPS, between its cities:start/end
// markers: the maps a first visit can open, the locate button can offer and the zoomed out pins show (every city page,
// built from index.html, carries the same list).
// Run after a city's build: node scripts/cities/configs.mjs
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PUBLIC } from './public.mjs';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const KEEP = ['id', 'name', 'region', 'tz', 'center', 'zoom', 'bounds', 'holidays', 'holidayRule', 'cityHolidays', 'fine', 'tow', 'winter'];
const ids = fs.readdirSync(ROOT + 'data', { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== 'boston' && fs.existsSync(`${ROOT}data/${d.name}/city.json`) && fs.existsSync(`${ROOT}data/${d.name}/segments.json`))
  .map((d) => d.name).sort();

const configs = {};
for (const id of ids) {
  const c = JSON.parse(fs.readFileSync(`${ROOT}data/${id}/city.json`, 'utf8'));
  if (c.id !== id) throw new Error(`data/${id}/city.json: id is "${c.id}", not "${id}"`);
  for (const k of ['tz', 'center', 'zoom', 'bounds', 'holidays']) if (c[k] == null) throw new Error(`data/${id}/city.json: no ${k}`);
  configs[id] = Object.fromEntries(KEEP.filter((k) => c[k] != null).map((k) => [k, c[k]]));
}

const out = `/* GENERATED by scripts/cities/configs.mjs from data/<id>/city.json. Do not edit: change the city's build and rerun.
   The runtime facts of every city built by docs/multi-city/city-build.md, for lib/city.js (pages) and lib/cities.js
   (alerts). A plain script attached to globalThis, like lib/sweep-core.js. */
(function (root) {
  root.CITY_CONFIGS = ${JSON.stringify(configs, null, 1)};
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(ROOT + 'lib/city-configs.js', out);
console.error(`[configs] wrote lib/city-configs.js: ${ids.join(', ') || 'no cities yet'}`);

// index.html's CITY_MAPS: one line per public city, between the markers (San Francisco's entry stays as written there),
// the biggest maps first (by blocks), so a numbered pin of crowded cities is named after the biggest one
for (const id of PUBLIC) if (!configs[id]) throw new Error(`scripts/cities/public.mjs lists ${id}, which has no data/${id}/city.json and segments.json`);
const blocks = Object.fromEntries(PUBLIC.map((id) => [id, JSON.parse(fs.readFileSync(`${ROOT}data/${id}/segments.json`, 'utf8')).b.length]));
const lines = [...PUBLIC].sort((a, b) => blocks[b] - blocks[a] || a.localeCompare(b)).map((id) => {
  const c = configs[id];
  return JSON.stringify({ id, name: c.name, region: c.region, path: '/' + id, center: c.center, bounds: c.bounds }) + ',';
});
const html = fs.readFileSync(ROOT + 'index.html', 'utf8');
const marked = /(\/\* cities:start \*\/\n)[\s\S]*?(\/\* cities:end \*\/)/;
if (!marked.test(html)) throw new Error('index.html has no /* cities:start */ ... /* cities:end */ markers in CITY_MAPS');
const next = html.replace(marked, (_, a, b) => a + lines.map((l) => l + '\n').join('') + b);
if (next !== html) fs.writeFileSync(ROOT + 'index.html', next);
console.error(`[configs] index.html CITY_MAPS: ${PUBLIC.length} public cities`);
